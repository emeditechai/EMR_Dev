using System.Globalization;
using ClosedXML.Excel;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;

namespace EMR.Web.Services.Reports;

/// <summary>What the export prints above the data.</summary>
public sealed record TestWorkloadExportInfo(string BranchName, DateTime From, DateTime To, IReadOnlyList<string> Filters, string GeneratedBy, DateTime GeneratedAt);

/// <summary>LAB > Testwise Workload, server-side Excel (all three views as sheets) and PDF (the chosen view).</summary>
public static class LabTestWorkloadExport
{
    public const string ViewSummary = "summary", ViewPatients = "patients", ViewDetails = "details";

    private static string Date(DateTime d) => d.ToString("dd MMM yyyy", CultureInfo.InvariantCulture);
    private static string Period(TestWorkloadExportInfo i) => i.From.Date == i.To.Date ? Date(i.From) : $"{Date(i.From)} to {Date(i.To)}";
    public static string Hours(double? h) => h is null ? "-" : h.Value < 1 ? $"{Math.Round(h.Value * 60)} min" : $"{h.Value:0.0} h";
    public static string Pct(double? p) => p is null ? "-" : $"{p.Value:0}%";

    private static IEnumerable<IGrouping<string, TestWorkloadRow>> ByDepartment(TestWorkloadResult r) =>
        r.Rows.GroupBy(x => x.Department).OrderBy(g => g.Key);

    /// <summary>The department's subtotal (worked out from its lines, so a patient is counted once per department).</summary>
    private static TestWorkloadRow Sub(TestWorkloadResult r, string dept) =>
        r.Departments.TryGetValue(dept, out var d) ? d : new TestWorkloadRow { TestName = dept + " - subtotal" };

    // ── column sets shared by Excel and PDF ──
    private static readonly (string Head, Func<TestWorkloadRow, object?> Get)[] SummaryCols =
    [
        ("Patients", r => r.Patients), ("Bills", r => r.Bills), ("Tests", r => r.Tests), ("Urgent", r => r.Urgent),
        ("B2C", r => r.B2C), ("B2B", r => r.B2B), ("Direct", r => r.SingleTest), ("In Package", r => r.InPackage),
        ("Pending Collection", r => r.PendingCollection), ("Collected", r => r.Collected), ("Re-collect", r => r.ReCollect), ("Rejected", r => r.Rejected),
        ("Pending Entry", r => r.PendingEntry), ("Entered", r => r.Entered), ("Validated", r => r.Validated), ("Approved", r => r.Approved),
        ("Outsourced", r => r.Outsourced), ("Abnormal", r => r.Abnormal), ("Critical", r => r.Critical),
        ("Avg TAT", r => Hours(r.AvgTatHours)), ("Within TAT", r => r.WithinTat), ("Delayed", r => r.Delayed), ("Overdue", r => r.Overdue),
        ("TAT Compliance", r => Pct(r.TatCompliance)), ("Cancelled", r => r.Cancelled)
    ];

    private static readonly (string Head, Func<TestWorkloadRow, object?> Get)[] PatientCols =
    [
        ("Patients", r => r.Patients), ("Tests", r => r.Tests), ("Bills", r => r.Bills), ("Male", r => r.Male), ("Female", r => r.Female),
        ("Other / NA", r => r.OtherGender), ("Under 18", r => r.Children), ("18 - 59", r => r.Adults), ("60 +", r => r.Seniors),
        ("Repeat Patients", r => r.RepeatPatients), ("Tests / Patient", r => r.Patients == 0 ? "-" : (r.Tests / (double)r.Patients).ToString("0.0"))
    ];

    // ═══════════════════════════════ Excel ═══════════════════════════════
    private static readonly XLColor Brand = XLColor.FromHtml("#644098");
    private static readonly XLColor DeptFill = XLColor.FromHtml("#F1ECF8");
    private static readonly XLColor TotalFill = XLColor.FromHtml("#E9E3F3");

    public static byte[] BuildExcel(TestWorkloadResult r, TestWorkloadExportInfo info)
    {
        using var wb = new XLWorkbook();
        WriteGrid(wb.Worksheets.Add("Workload Summary"), "Testwise Workload - Summary", r, info, SummaryCols);
        WriteGrid(wb.Worksheets.Add("Patient Count"), "Testwise Workload - Patient Count", r, info, PatientCols);
        WriteDetails(wb.Worksheets.Add("Patient-wise Details"), r, info);
        using var ms = new MemoryStream();
        wb.SaveAs(ms);
        return ms.ToArray();
    }

    private static int Title(IXLWorksheet ws, string title, TestWorkloadExportInfo info, int lastCol)
    {
        ws.Cell(1, 1).Value = title;
        ws.Cell(1, 1).Style.Font.SetBold().Font.SetFontSize(14).Font.SetFontColor(Brand);
        ws.Cell(2, 1).Value = $"{(string.IsNullOrWhiteSpace(info.BranchName) ? "" : "Branch: " + info.BranchName + "   ")}Bill date: {Period(info)}";
        ws.Cell(3, 1).Value = info.Filters.Count > 0 ? "Filters: " + string.Join(" · ", info.Filters) : "Filters: none";
        ws.Cell(4, 1).Value = $"Counts are per test of the Investigation Master (a profile counts as one test; a package counts as the profiles and tests in it). Generated by {info.GeneratedBy} on {info.GeneratedAt:dd MMM yyyy, hh:mm tt}";
        ws.Range(2, 1, 4, 1).Style.Font.SetFontColor(XLColor.FromHtml("#475569"));
        for (var row = 1; row <= 4; row++) ws.Range(row, 1, row, lastCol).Merge();
        return 6;
    }

    private static void Head(IXLWorksheet ws, int row, IReadOnlyList<string> heads)
    {
        for (var c = 0; c < heads.Count; c++) ws.Cell(row, c + 1).Value = heads[c];
        var rg = ws.Range(row, 1, row, heads.Count);
        rg.Style.Font.SetBold().Font.SetFontColor(XLColor.White).Fill.SetBackgroundColor(Brand);
        rg.Style.Alignment.SetWrapText(true).Alignment.SetVertical(XLAlignmentVerticalValues.Center);
    }

    private static void Put(IXLCell cell, object? v)
    {
        switch (v)
        {
            case int i: cell.Value = i; break;
            case double d: cell.Value = d; break;
            case null: break;
            default: cell.Value = v.ToString(); cell.Style.Alignment.SetHorizontal(XLAlignmentHorizontalValues.Right); break;
        }
    }

    private static void WriteGrid(IXLWorksheet ws, string title, TestWorkloadResult r, TestWorkloadExportInfo info,
                                  (string Head, Func<TestWorkloadRow, object?> Get)[] cols)
    {
        var heads = new List<string> { "#", "Test Code", "Test Name", "Category", "Sub Category", "TAT (h)" };
        heads.AddRange(cols.Select(c => c.Head));
        var row = Title(ws, title, info, heads.Count);
        Head(ws, row, heads);
        var headRow = row++;
        var n = 0;

        void Line(TestWorkloadRow x, bool numbered)
        {
            if (numbered) ws.Cell(row, 1).Value = ++n;
            ws.Cell(row, 2).Value = x.TestCode;
            ws.Cell(row, 3).Value = x.IsProfile ? x.TestName + " [Profile]" : x.TestName;
            ws.Cell(row, 4).Value = x.Category;
            ws.Cell(row, 5).Value = x.SubCategory;
            if (x.TatHours > 0) ws.Cell(row, 6).Value = x.TatHours;
            for (var c = 0; c < cols.Length; c++) Put(ws.Cell(row, 7 + c), cols[c].Get(x));
            row++;
        }

        foreach (var dept in ByDepartment(r))
        {
            ws.Cell(row, 1).Value = dept.Key;
            ws.Range(row, 1, row, heads.Count).Style.Font.SetBold().Fill.SetBackgroundColor(DeptFill);
            row++;
            foreach (var x in dept) Line(x, true);
            var subRow = row;
            Line(Sub(r, dept.Key), false);
            ws.Range(subRow, 1, subRow, heads.Count).Style.Font.SetBold().Font.SetItalic();
        }
        if (r.Rows.Count > 0)
        {
            var totRow = row;
            Line(r.Total, false);
            ws.Range(totRow, 1, totRow, heads.Count).Style.Font.SetBold().Fill.SetBackgroundColor(TotalFill);
        }
        else ws.Cell(row, 1).Value = "No tests for the selected filters.";

        ws.SheetView.FreezeRows(headRow);
        ws.SheetView.FreezeColumns(3);
        ws.Columns(1, heads.Count).AdjustToContents(headRow, row, 8, 40);
        ws.Column(3).Width = Math.Max(ws.Column(3).Width, 28);
        if (row > headRow + 1) ws.Range(headRow, 1, row - 1, heads.Count).SetAutoFilter();
    }

    private static readonly string[] DetailHeads =
    [
        "#", "Bill Date", "Bill No", "Token", "Billing", "Urgent", "Patient ID", "Patient Name", "Age", "Gender", "Phone",
        "Test Code", "Test Name", "Department", "Category", "Sub Category", "Ordered", "Sample Status", "Collected At",
        "Report Status", "Approved At", "TAT (h)", "Time Taken", "TAT Status", "Abnormal", "Outsourced", "Branch"
    ];

    private static void WriteDetails(IXLWorksheet ws, TestWorkloadResult r, TestWorkloadExportInfo info)
    {
        var row = Title(ws, "Testwise Workload - Patient-wise Details", info, DetailHeads.Length);
        Head(ws, row, DetailHeads);
        var headRow = row++;
        var now = DateTime.Now;
        var n = 0;
        foreach (var l in OrderedLines(r))
        {
            var c = 1;
            ws.Cell(row, c++).Value = ++n;
            ws.Cell(row, c).Value = l.BillDate; ws.Cell(row, c++).Style.DateFormat.Format = "dd-MMM-yyyy hh:mm AM/PM";
            ws.Cell(row, c++).Value = l.BillNo ?? "";
            ws.Cell(row, c++).Value = l.TokenNo ?? "";
            ws.Cell(row, c++).Value = l.IsB2B ? "B2B" : "B2C";
            ws.Cell(row, c++).Value = l.IsUrgent ? "Yes" : "";
            ws.Cell(row, c++).Value = l.PatientCode ?? "";
            ws.Cell(row, c++).Value = l.PatientName ?? "";
            if (l.Age is { } age) ws.Cell(row, c).Value = age; c++;
            ws.Cell(row, c++).Value = l.GenderShort;
            ws.Cell(row, c++).Value = l.PhoneNumber ?? "";
            ws.Cell(row, c++).Value = l.TestCode ?? "";
            ws.Cell(row, c++).Value = l.IsProfile ? $"{l.TestName} [Profile, {l.Parts} tests]" : l.TestName ?? "";
            ws.Cell(row, c++).Value = l.DepartmentName ?? "";
            ws.Cell(row, c++).Value = l.CategoryName ?? "";
            ws.Cell(row, c++).Value = l.SubCategoryName ?? "";
            ws.Cell(row, c++).Value = l.Source;
            ws.Cell(row, c++).Value = l.SampleStatus;
            if (l.CollectedAt is { } ca) { ws.Cell(row, c).Value = ca; ws.Cell(row, c).Style.DateFormat.Format = "dd-MMM-yyyy hh:mm AM/PM"; } c++;
            ws.Cell(row, c++).Value = l.ReportStatus;
            if (l.IsApproved && l.ApprovedAt is { } aa) { ws.Cell(row, c).Value = aa; ws.Cell(row, c).Style.DateFormat.Format = "dd-MMM-yyyy hh:mm AM/PM"; } c++;
            ws.Cell(row, c++).Value = l.TatHours;
            ws.Cell(row, c++).Value = l.TatTakenHours is null ? "" : Hours(l.TatTakenHours);
            ws.Cell(row, c++).Value = l.TatStatus(now);
            ws.Cell(row, c++).Value = l.IsAbnormal ? (l.AbnormalFlag == "Critical" ? "Critical" : l.AbnormalFlag == "Abnormal" ? "Yes" : l.AbnormalFlag) : "";
            ws.Cell(row, c++).Value = l.IsOutsourced ? "Yes" : "";
            ws.Cell(row, c++).Value = l.BranchName ?? "";
            if (l.IsCancelled) ws.Range(row, 1, row, DetailHeads.Length).Style.Font.SetFontColor(XLColor.FromHtml("#94A3B8")).Font.SetStrikethrough();
            row++;
        }
        if (n == 0) ws.Cell(row, 1).Value = "No tests for the selected filters.";
        ws.SheetView.FreezeRows(headRow);
        ws.Columns(1, DetailHeads.Length).AdjustToContents(headRow, Math.Max(row, headRow + 1), 6, 36);
        if (n > 0) ws.Range(headRow, 1, row - 1, DetailHeads.Length).SetAutoFilter();
    }

    /// <summary>Patient-wise details in report order: test by test (department, test name), then by bill date.</summary>
    public static IEnumerable<TestWorkloadLine> OrderedLines(TestWorkloadResult r) =>
        r.Lines.OrderBy(l => l.DepartmentName).ThenBy(l => l.TestName).ThenBy(l => l.BillDate).ThenBy(l => l.LabOrderId);

    // ═══════════════════════════════ PDF ═══════════════════════════════
    private const string PdfBrand = "#644098", PdfInk = "#1E293B", PdfMuted = "#64748B", PdfLine = "#E2E8F0", PdfDept = "#F1ECF8", PdfTotal = "#E9E3F3";

    public static byte[] BuildPdf(TestWorkloadResult r, TestWorkloadExportInfo info, string view)
    {
        QuestPDF.Settings.License = LicenseType.Community;
        var (title, subtitle) = view switch
        {
            ViewPatients => ("Testwise Workload - Patient Count", "Patients tested per test, by gender and age"),
            ViewDetails => ("Testwise Workload - Patient-wise Details", "Every test of every bill, test by test"),
            _ => ("Testwise Workload - Summary", "All workload parameters per test")
        };

        return Document.Create(doc => doc.Page(page =>
        {
            page.Size(PageSizes.A4.Landscape());
            page.Margin(18);
            page.DefaultTextStyle(t => t.FontSize(view == ViewSummary ? 6.5f : 7.5f).FontColor(PdfInk));

            page.Header().Column(h =>
            {
                h.Item().Row(rw =>
                {
                    rw.RelativeItem().Column(c =>
                    {
                        c.Item().Text(title).FontSize(14).Bold().FontColor(PdfBrand);
                        c.Item().Text(subtitle + " · counts per test of the Investigation Master").FontSize(8).FontColor(PdfMuted);
                    });
                    rw.RelativeItem().AlignRight().Column(c =>
                    {
                        if (!string.IsNullOrWhiteSpace(info.BranchName)) c.Item().AlignRight().Text("Branch: " + info.BranchName).FontSize(8).SemiBold();
                        c.Item().AlignRight().Text("Bill date: " + Period(info)).FontSize(8);
                    });
                });
                if (info.Filters.Count > 0) h.Item().PaddingTop(2).Text("Filters: " + string.Join(" · ", info.Filters)).FontSize(7).FontColor(PdfMuted);
                h.Item().PaddingTop(3).Element(e => Kpis(e, r));
                h.Item().PaddingTop(4).LineHorizontal(1).LineColor(PdfBrand);
            });

            page.Content().PaddingTop(5).Element(e =>
            {
                if (view == ViewDetails) DetailsTable(e, r);
                else GridTable(e, r, view == ViewPatients ? PatientCols : SummaryCols, view == ViewSummary);
            });

            page.Footer().BorderTop(0.5f).BorderColor(PdfLine).PaddingTop(3).Row(rw =>
            {
                rw.RelativeItem().Text($"Generated by {info.GeneratedBy} on {info.GeneratedAt:dd MMM yyyy, hh:mm tt}").FontSize(7).FontColor(PdfMuted);
                rw.RelativeItem().AlignRight().Text(t =>
                {
                    t.DefaultTextStyle(s => s.FontSize(7).FontColor(PdfMuted));
                    t.Span("Page "); t.CurrentPageNumber(); t.Span(" of "); t.TotalPages();
                });
            });
        })).GeneratePdf();
    }

    private static void Kpis(IContainer c, TestWorkloadResult r)
    {
        var t = r.Total;
        (string Label, string Value)[] k =
        [
            ("Tests", t.Tests.ToString("N0")), ("Patients", t.Patients.ToString("N0")), ("Bills", t.Bills.ToString("N0")),
            ("Distinct tests", r.DistinctTests.ToString("N0")), ("Approved", $"{t.Approved:N0} ({Pct(t.ApprovedPercent)})"),
            ("Avg TAT", Hours(t.AvgTatHours)), ("TAT compliance", Pct(t.TatCompliance)), ("Abnormal", t.Abnormal.ToString("N0"))
        ];
        c.Row(row =>
        {
            row.Spacing(4);
            foreach (var (label, value) in k)
                row.RelativeItem().Border(0.5f).BorderColor(PdfLine).Background("#FAF9FC").Padding(3).Column(col =>
                {
                    col.Item().Text(label.ToUpperInvariant()).FontSize(5.5f).FontColor(PdfMuted).SemiBold();
                    col.Item().Text(value).FontSize(9).Bold();
                });
        });
    }

    private static void GridTable(IContainer c, TestWorkloadResult r, (string Head, Func<TestWorkloadRow, object?> Get)[] cols, bool compact)
    {
        c.Table(t =>
        {
            t.ColumnsDefinition(cd =>
            {
                cd.ConstantColumn(16);
                cd.RelativeColumn(compact ? 3.2f : 4f);
                cd.ConstantColumn(compact ? 22 : 30);
                foreach (var _ in cols) cd.RelativeColumn(1);
            });
            t.Header(h =>
            {
                static IContainer H(IContainer x) => x.Background(PdfBrand).PaddingVertical(3).PaddingHorizontal(2);
                h.Cell().Element(H).AlignBottom().Text("#").FontColor(Colors.White).Bold();
                h.Cell().Element(H).AlignBottom().Text("Test").FontColor(Colors.White).Bold();
                if (compact) h.Cell().Element(H).Height(58).AlignBottom().AlignCenter().RotateLeft().AlignMiddle().Text("TAT (h)").FontColor(Colors.White).Bold();
                else h.Cell().Element(H).AlignRight().Text("TAT h").FontColor(Colors.White).Bold();
                // many columns: the headings stand upright so none is broken in the middle of a word
                foreach (var col in cols)
                {
                    if (compact) h.Cell().Element(H).Height(58).AlignBottom().AlignCenter().RotateLeft().AlignMiddle().Text(col.Head).FontColor(Colors.White).Bold();
                    else h.Cell().Element(H).AlignRight().Text(col.Head).FontColor(Colors.White).Bold();
                }
            });

            var n = 0;
            void Row(TestWorkloadRow x, string? bg, bool bold, bool numbered)
            {
                IContainer Cell(IContainer cc) => (bg is null ? cc : cc.Background(bg)).BorderBottom(0.5f).BorderColor(PdfLine).PaddingVertical(2).PaddingHorizontal(2);
                var num = numbered ? (++n).ToString() : "";
                t.Cell().Element(Cell).Text(num).FontColor(PdfMuted);
                t.Cell().Element(Cell).Text(tx =>
                {
                    var s = tx.Span(x.TestName); if (bold) s.Bold();
                    if (x.IsProfile) tx.Span("  PROFILE").FontColor(PdfBrand).FontSize(5).SemiBold();
                    if (!string.IsNullOrWhiteSpace(x.TestCode)) tx.Span("  " + x.TestCode).FontColor(PdfMuted).FontSize(5.5f);
                });
                t.Cell().Element(Cell).AlignRight().Text(x.TatHours > 0 ? x.TatHours.ToString() : "");
                foreach (var col in cols)
                {
                    var v = col.Get(x);
                    var text = v is int i ? (i == 0 ? "-" : i.ToString("N0")) : v?.ToString() ?? "";
                    var span = t.Cell().Element(Cell).AlignRight().Text(text);
                    if (bold) span.Bold();
                }
            }

            foreach (var dept in ByDepartment(r))
            {
                t.Cell().ColumnSpan((uint)(3 + cols.Length)).Background(PdfDept).PaddingVertical(2).PaddingHorizontal(3).Text(dept.Key).Bold().FontColor(PdfBrand);
                foreach (var x in dept) Row(x, null, false, true);
                Row(Sub(r, dept.Key), "#FAF9FC", true, false);
            }
            if (r.Rows.Count == 0)
                t.Cell().ColumnSpan((uint)(3 + cols.Length)).PaddingVertical(20).AlignCenter().Text("No tests for the selected filters.").FontColor(PdfMuted);
            else
            {
                Row(r.Total, PdfTotal, true, false);
            }
        });
    }

    private static void DetailsTable(IContainer c, TestWorkloadResult r)
    {
        var now = DateTime.Now;
        c.Table(t =>
        {
            t.ColumnsDefinition(cd =>
            {
                cd.ConstantColumn(20);   // #
                cd.ConstantColumn(56);   // bill date
                cd.RelativeColumn(1.4f); // bill no
                cd.RelativeColumn(2.2f); // patient
                cd.ConstantColumn(40);   // age / gender
                cd.RelativeColumn(1.1f); // ordered as
                cd.RelativeColumn(1f);   // sample
                cd.RelativeColumn(1f);   // report
                cd.ConstantColumn(56);   // approved at
                cd.ConstantColumn(40);   // time taken
                cd.ConstantColumn(46);   // TAT status
                cd.ConstantColumn(36);   // flag
            });
            t.Header(h =>
            {
                static IContainer H(IContainer x) => x.Background(PdfBrand).PaddingVertical(3).PaddingHorizontal(2);
                foreach (var head in new[] { "#", "Bill Date", "Bill No", "Patient", "Age / Sex", "Ordered", "Sample", "Report", "Approved At", "Time Taken", "TAT", "Flag" })
                    h.Cell().Element(H).Text(head).FontColor(Colors.White).Bold();
            });

            var n = 0;
            foreach (var test in OrderedLines(r).GroupBy(l => (l.TestId, l.TestName, l.TestCode, l.DepartmentName, l.TatHours)))
            {
                var live = test.Count(l => !l.IsCancelled);
                t.Cell().ColumnSpan(12).Background(PdfDept).PaddingVertical(2).PaddingHorizontal(3).Text(tx =>
                {
                    tx.Span(test.Key.TestName).Bold().FontColor(PdfBrand);
                    if (test.First().IsProfile) tx.Span("  PROFILE").FontColor(PdfBrand).FontSize(5.5f).SemiBold();
                    tx.Span($"  {test.Key.TestCode} · {test.Key.DepartmentName} · TAT {test.Key.TatHours} h · {live} test(s), {test.Where(l => !l.IsCancelled).Select(l => l.PatientId).Distinct().Count()} patient(s)").FontColor(PdfMuted);
                });
                foreach (var l in test)
                {
                    IContainer Cell(IContainer cc) => cc.BorderBottom(0.5f).BorderColor(PdfLine).PaddingVertical(2).PaddingHorizontal(2);
                    var faded = l.IsCancelled ? "#94A3B8" : PdfInk;
                    t.Cell().Element(Cell).Text((++n).ToString()).FontColor(PdfMuted);
                    t.Cell().Element(Cell).Text(l.BillDate.ToString("dd-MM-yy hh:mm tt")).FontColor(faded);
                    t.Cell().Element(Cell).Text(tx =>
                    {
                        tx.Span(l.BillNo ?? "").FontColor(faded);
                        tx.Span((l.IsB2B ? "  B2B" : "") + (l.IsUrgent ? "  Urgent" : "")).FontColor("#B91C1C").FontSize(6);
                    });
                    t.Cell().Element(Cell).Text(tx =>
                    {
                        tx.Span(l.PatientName ?? "").FontColor(faded);
                        if (!string.IsNullOrWhiteSpace(l.PatientCode)) tx.Span("  " + l.PatientCode).FontColor(PdfMuted).FontSize(6);
                    });
                    t.Cell().Element(Cell).Text($"{l.Age?.ToString() ?? "-"} / {(l.GenderShort.Length > 0 ? l.GenderShort[..1] : "-")}").FontColor(faded);
                    t.Cell().Element(Cell).Text(l.Source).FontColor(faded).FontSize(6.5f);
                    t.Cell().Element(Cell).Text(l.SampleStatus).FontColor(faded);
                    t.Cell().Element(Cell).Text(l.ReportStatus).FontColor(faded);
                    t.Cell().Element(Cell).Text(l.IsApproved && l.ApprovedAt is { } a ? a.ToString("dd-MM-yy hh:mm tt") : "").FontColor(faded);
                    t.Cell().Element(Cell).Text(l.TatTakenHours is null ? "" : Hours(l.TatTakenHours)).FontColor(faded);
                    var ts = l.TatStatus(now);
                    t.Cell().Element(Cell).Text(ts).FontColor(ts is "Delayed" or "Overdue" ? "#B91C1C" : ts == "Within TAT" ? "#15803D" : faded);
                    t.Cell().Element(Cell).Text(l.IsAbnormal ? l.AbnormalFlag ?? "" : "").FontColor(l.AbnormalFlag == "Critical" ? "#B91C1C" : faded).Bold();
                }
            }
            if (n == 0) t.Cell().ColumnSpan(12).PaddingVertical(20).AlignCenter().Text("No tests for the selected filters.").FontColor(PdfMuted);
        });
    }
}
