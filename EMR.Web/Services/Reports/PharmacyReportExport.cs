using System.Globalization;
using ClosedXML.Excel;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;

namespace EMR.Web.Services.Reports;

/// <summary>What a pharmacy report export prints above the data.</summary>
public sealed record PhRptExportInfo(string BranchName, DateTime From, DateTime To, IReadOnlyList<string> Filters, string GeneratedBy, DateTime GeneratedAt);

/// <summary>A run of a pharmacy report: tiles, rows and totals, each a row of column / value.</summary>
public sealed record PhRptResult(IDictionary<string, object?> Tiles, List<IDictionary<string, object?>> Rows, IDictionary<string, object?> Totals, int TotalRows);

/// <summary>Reports > Pharmacy, server-side Excel and PDF of any report defined in <see cref="PharmacyReportDefs"/>.</summary>
public static class PharmacyReportExport
{
    private static readonly CultureInfo In = CultureInfo.GetCultureInfo("en-IN");
    private const string Ink = "#0f172a", Muted = "#64748b", Accent = "#0f766e", Line = "#e2e8f0", Head = "#f1f5f9";

    public static string Format(object? v, string fmt)
    {
        if (v is null) return "";
        switch (fmt)
        {
            case "date": return v is DateTime d ? d.ToString("dd MMM yyyy", CultureInfo.InvariantCulture) : v.ToString()!;
            case "datetime": return v is DateTime t ? t.ToString("dd MMM yyyy, hh:mm tt", CultureInfo.InvariantCulture) : v.ToString()!;
        }
        if (!TryDec(v, out var n)) return v.ToString()!;
        return fmt switch
        {
            "money" => "₹" + n.ToString("#,##0.00", In),
            "int" => n.ToString("#,##0", In),
            "qty" or "num" => n.ToString("#,##0.##", In),
            "pct" => n.ToString("0.##", In) + "%",
            _ => v.ToString()!
        };
    }

    // relative PDF column widths: document numbers and mobiles on one line, short codes narrow
    private static float Width(PhRptCol c) => c.Field switch
    {
        "SaleNo" or "DocNo" or "ReturnNo" or "LastBillNo" or "GrnNo" or "PoNo" or "PaymentNo" or "IndentNo" => 1.9f,
        "Mobile" => 1.4f,
        "BranchCode" or "Status" or "ScheduleCode" or "SaleUom" or "FormShort" => 0.8f,
        _ => c.Fmt switch { "money" => 1.25f, "int" or "pct" => 0.8f, "qty" or "num" => 0.9f, "datetime" => 1.5f, _ => 1.3f }
    };

    /// <summary>A table cell of the PDF: amounts without the ₹ sign (the column heading carries it) so they stay on one line.</summary>
    private static string Cell(object? v, string fmt) => fmt == "money" && TryDec(v, out var n) ? n.ToString("#,##0.00", In) : Format(v, fmt);

    private static bool TryDec(object? v, out decimal n)
    {
        switch (v)
        {
            case int i: n = i; return true;
            case long l: n = l; return true;
            case decimal m: n = m; return true;
            case double d: n = (decimal)d; return true;
            default: n = 0; return false;
        }
    }

    private static bool Numeric(string fmt) => fmt is "money" or "int" or "qty" or "num" or "pct";
    private static string Period(PhRptDef def, PhRptExportInfo i) =>
        def.DateMode == "none" ? "As on " + i.GeneratedAt.ToString("dd MMM yyyy", CultureInfo.InvariantCulture)
        : i.From.Date == i.To.Date ? i.From.ToString("dd MMM yyyy", CultureInfo.InvariantCulture)
        : $"{i.From:dd MMM yyyy} – {i.To:dd MMM yyyy}";

    public static byte[] BuildExcel(PhRptDef def, PhRptResult r, PhRptExportInfo info)
    {
        using var wb = new XLWorkbook();
        var ws = wb.Worksheets.Add(def.Code);
        var cols = def.Cols;
        ws.Cell(1, 1).Value = $"{def.Code} · {def.Title}";
        ws.Cell(1, 1).Style.Font.SetBold().Font.SetFontSize(14).Font.SetFontColor(XLColor.FromHtml(Accent));
        ws.Cell(2, 1).Value = $"Branch: {info.BranchName}   ·   Period: {Period(def, info)}";
        var row = 3;
        if (info.Filters.Count > 0) ws.Cell(row++, 1).Value = "Filters: " + string.Join(" · ", info.Filters);
        ws.Cell(row++, 1).Value = $"Generated by {info.GeneratedBy} on {info.GeneratedAt:dd MMM yyyy, hh:mm tt}";
        ws.Range(2, 1, row - 1, 1).Style.Font.SetFontColor(XLColor.FromHtml(Muted));

        // tiles as label / value pairs on one row
        row++;
        var tc = 1;
        foreach (var t in def.Tiles)
        {
            ws.Cell(row, tc).Value = t.Label;
            ws.Cell(row, tc).Style.Font.SetFontColor(XLColor.FromHtml(Muted)).Font.SetFontSize(9);
            ws.Cell(row + 1, tc).Value = Format(r.Tiles.TryGetValue(t.Field, out var tv) ? tv : null, t.Fmt);
            ws.Cell(row + 1, tc).Style.Font.SetBold();
            tc += 2;
        }
        row += 3;

        var head = row;
        ws.Cell(row, 1).Value = "#";
        for (var c = 0; c < cols.Length; c++) ws.Cell(row, c + 2).Value = cols[c].Label;
        var hr = ws.Range(row, 1, row, cols.Length + 1);
        hr.Style.Font.SetBold().Fill.SetBackgroundColor(XLColor.FromHtml(Head)).Border.SetBottomBorder(XLBorderStyleValues.Thin);
        row++;

        var n = 0;
        foreach (var d in r.Rows)
        {
            ws.Cell(row, 1).Value = ++n;
            for (var c = 0; c < cols.Length; c++) SetCell(ws.Cell(row, c + 2), d.TryGetValue(cols[c].Field, out var v) ? v : null, cols[c].Fmt);
            row++;
        }
        if (r.Rows.Count == 0) ws.Cell(row++, 2).Value = "No records for the selected filters.";

        ws.Cell(row, 2).Value = $"Total ({r.TotalRows:#,##0} rows)";
        for (var c = 0; c < cols.Length; c++)
            if (cols[c].Total && r.Totals.TryGetValue(cols[c].Field, out var tv)) SetCell(ws.Cell(row, c + 2), tv, cols[c].Fmt);
        ws.Range(row, 1, row, cols.Length + 1).Style.Font.SetBold().Fill.SetBackgroundColor(XLColor.FromHtml(Head)).Border.SetTopBorder(XLBorderStyleValues.Thin);

        ws.SheetView.FreezeRows(head);
        ws.Range(head, 1, row, cols.Length + 1).SetAutoFilter();
        ws.Columns(1, cols.Length + 1).AdjustToContents(head, row, 8, 45);
        using var ms = new MemoryStream();
        wb.SaveAs(ms);
        return ms.ToArray();
    }

    private static void SetCell(IXLCell cell, object? v, string fmt)
    {
        if (v is null) return;
        if (Numeric(fmt) && TryDec(v, out var n))
        {
            cell.Value = fmt == "pct" ? n / 100m : n;
            cell.Style.NumberFormat.Format = fmt switch { "money" => "#,##0.00", "int" => "#,##0", "pct" => "0.00%", _ => "#,##0.##" };
        }
        else if (v is DateTime d)
        {
            cell.Value = d;
            cell.Style.NumberFormat.Format = fmt == "date" ? "dd-mmm-yyyy" : "dd-mmm-yyyy hh:mm AM/PM";
        }
        else cell.Value = v.ToString();
    }

    public static byte[] BuildPdf(PhRptDef def, PhRptResult r, PhRptExportInfo info)
    {
        var cols = def.Cols;
        return Document.Create(doc => doc.Page(page =>
        {
            page.Size(cols.Length > 9 ? PageSizes.A4.Landscape() : PageSizes.A4);
            page.Margin(20);
            page.DefaultTextStyle(t => t.FontSize(cols.Length > 16 ? 6f : cols.Length > 12 ? 6.8f : 7.5f).FontColor(Ink));

            page.Header().Column(h =>
            {
                h.Item().Row(rw =>
                {
                    rw.RelativeItem().Column(c =>
                    {
                        c.Item().Text($"{def.Title}").FontSize(14).Bold().FontColor(Accent);
                        c.Item().Text($"{def.Code} · Pharmacy · {def.Subtitle}").FontSize(8).FontColor(Muted);
                    });
                    rw.RelativeItem().AlignRight().Column(c =>
                    {
                        c.Item().AlignRight().Text("Branch: " + info.BranchName).SemiBold();
                        c.Item().AlignRight().Text("Period: " + Period(def, info));
                    });
                });
                if (info.Filters.Count > 0) h.Item().PaddingTop(2).Text("Filters: " + string.Join(" · ", info.Filters)).FontSize(7).FontColor(Muted);
                h.Item().PaddingTop(4).LineHorizontal(1).LineColor(Accent);
            });

            page.Content().PaddingTop(6).Column(col =>
            {
                col.Spacing(6);
                col.Item().Row(rw =>
                {
                    rw.Spacing(6);
                    foreach (var t in def.Tiles)
                        rw.RelativeItem().Border(0.5f).BorderColor(Line).Padding(5).Column(c =>
                        {
                            c.Item().Text(t.Label.ToUpperInvariant()).FontSize(6).FontColor(Muted).SemiBold();
                            c.Item().Text(Format(r.Tiles.TryGetValue(t.Field, out var tv) ? tv : null, t.Fmt)).FontSize(10).Bold();
                        });
                });

                col.Item().Table(tb =>
                {
                    tb.ColumnsDefinition(cd =>
                    {
                        cd.ConstantColumn(22);
                        foreach (var c in cols) cd.RelativeColumn(Width(c));
                    });
                    tb.Header(hd =>
                    {
                        hd.Cell().Background(Head).Padding(3).Text("#").SemiBold();
                        foreach (var c in cols)
                        {
                            var cell = hd.Cell().Background(Head).Padding(3);
                            (Numeric(c.Fmt) ? cell.AlignRight() : cell).Text(c.Fmt == "money" ? c.Label + " (₹)" : c.Label).SemiBold().FontColor(Muted);
                        }
                    });
                    var n = 0;
                    foreach (var d in r.Rows)
                    {
                        n++;
                        tb.Cell().BorderBottom(0.4f).BorderColor(Line).Padding(3).Text(n.ToString(In));
                        foreach (var c in cols)
                        {
                            var cell = tb.Cell().BorderBottom(0.4f).BorderColor(Line).Padding(3);
                            var s = Cell(d.TryGetValue(c.Field, out var v) ? v : null, c.Fmt);
                            (Numeric(c.Fmt) ? cell.AlignRight() : cell).Text(s);
                        }
                    }
                    tb.Cell().ColumnSpan(2).Background(Head).Padding(3).Text($"Total ({r.TotalRows:#,##0})").Bold();
                    foreach (var c in cols.Skip(1))
                    {
                        var cell = tb.Cell().Background(Head).Padding(3);
                        var s = c.Total && r.Totals.TryGetValue(c.Field, out var tv) ? Cell(tv, c.Fmt) : "";
                        (Numeric(c.Fmt) ? cell.AlignRight() : cell).Text(s).Bold();
                    }
                });
                if (r.Rows.Count == 0) col.Item().PaddingTop(16).AlignCenter().Text("No records for the selected filters.").FontColor(Muted);
            });

            page.Footer().BorderTop(0.5f).BorderColor(Line).PaddingTop(3).Row(rw =>
            {
                rw.RelativeItem().Text($"Generated by {info.GeneratedBy} on {info.GeneratedAt:dd MMM yyyy, hh:mm tt}").FontSize(7).FontColor(Muted);
                rw.RelativeItem().AlignRight().Text(t =>
                {
                    t.DefaultTextStyle(s => s.FontSize(7).FontColor(Muted));
                    t.Span("Page "); t.CurrentPageNumber(); t.Span(" of "); t.TotalPages();
                });
            });
        })).GeneratePdf();
    }
}
