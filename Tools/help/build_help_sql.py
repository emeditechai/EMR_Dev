"""
Builds SQLScripts/2300_help_center.sql from Tools/help/help_content.py.

    python3 Tools/help/build_help_sql.py

Re-run after editing the content, then run the script on the database (safe to re-run: the seeded articles are
replaced, feedback is kept).
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
import help_content as hc  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "SQLScripts", "2300_help_center.sql")


def q(s):
    return "N'" + str(s).replace("'", "''") + "'"


def main():
    rows = []
    for i, m in enumerate(hc.MODULES):
        body = {"menus": m["menus"], "icon": m["icon"], "setup": [{"page": p, "why": w} for p, w in m["setup"]]}
        rows.append(("MOD." + m["code"], "MODULE", m["code"], m["title"], m["summary"], ",".join(m["menus"]), "", body, i * 10))
    for i, a in enumerate(hc.ARTICLES):
        body = {"steps": a["steps"], "prereq": a["prereq"], "tips": a["tips"], "next": a["next"]}
        rows.append((a["code"], a["kind"], a["module"], a["title"], a["summary"], ",".join(a["pages"]), a["keywords"], body, i * 10))

    # workflows: the written ones, then each module's setup order as a "Set up <module>" workflow
    guide_of_page = {}
    for a in hc.ARTICLES:
        if a["kind"] == "GUIDE":
            for p in a["pages"]:
                guide_of_page.setdefault(p, a["code"])
    flows = list(hc.WORKFLOWS)
    for m in hc.MODULES:
        if m["setup"]:
            flows.append(dict(code="FLOW.SETUP." + m["code"], module=m["code"], title=f"Set up {m['title']} - in this order",
                              summary=f"What to set up for {m['title']}, each step depending on the ones before it.",
                              steps=[hc.step(p, "", why, guide_of_page.get(p)) for p, why in m["setup"]],
                              keywords=f"configure {m['title'].lower()} masters"))
    for i, f in enumerate(flows):
        body = {"flow": f["steps"], "primary": f.get("primary", False), "steps": [(s["title"] + (f" ({s['when']})" if s["when"] else "") + ": " if s["title"] else "") + s["do"] for s in f["steps"]]}
        pages = list(dict.fromkeys(s["page"] for s in f["steps"]))
        rows.append((f["code"], "FLOW", f["module"], f["title"], f["summary"], ",".join(pages), f["keywords"], body, 5000 + i * 10))

    codes = [r[0] for r in rows]
    dup = {c for c in codes if codes.count(c) > 1}
    if dup:
        raise SystemExit("Duplicate article codes: " + ", ".join(sorted(dup)))

    out = []
    w = out.append
    w("""-- ============================================================================================================
-- Migration: 2300_help_center.sql   (GENERATED by Tools/help/build_help_sql.py from Tools/help/help_content.py)
-- Utility > Help Center: the user guide of the whole application - module overviews with their setup order,
-- step-by-step guides (before you start / steps / tips / next), workflows (the order of work), FAQs, troubleshooting, help for every page
-- (built from the menu and its actions when no guide is written), the Help Assistant (asks in plain words) and
-- "was this helpful" feedback. Data goes EMR.Web -> EMR.Api (api/help) -> the procedures below.
-- Adds the tables, the procedures, the seeded content (replaced on every run, feedback kept) and the page under
-- Utility. The Help Center opens for every signed-in user; no role grants change. Safe to re-run.
-- ============================================================================================================
SET ANSI_NULLS ON;
GO
SET QUOTED_IDENTIFIER ON;
GO

IF OBJECT_ID(N'dbo.HelpArticle', N'U') IS NULL
CREATE TABLE dbo.HelpArticle
(
    ArticleId    INT IDENTITY(1, 1) NOT NULL CONSTRAINT PK_HelpArticle PRIMARY KEY,
    Code         VARCHAR(60)    NOT NULL CONSTRAINT UX_HelpArticle_Code UNIQUE,
    Kind         VARCHAR(10)    NOT NULL CONSTRAINT CK_HelpArticle_Kind CHECK (Kind IN ('MODULE', 'GUIDE', 'FAQ', 'TROUBLE', 'FLOW')),
    Module       VARCHAR(20)    NOT NULL,
    Title        NVARCHAR(200)  NOT NULL,
    Summary      NVARCHAR(1000) NOT NULL,
    PageCodes    NVARCHAR(1000) NULL,            -- pages the article explains (comma separated Page_Code)
    Keywords     NVARCHAR(500)  NULL,
    BodyJson     NVARCHAR(MAX)  NOT NULL,        -- steps / prereq / tips / next (or the module's setup order)
    SortOrder    INT            NOT NULL CONSTRAINT DF_HelpArticle_Sort DEFAULT (0),
    Source       VARCHAR(10)    NOT NULL CONSTRAINT DF_HelpArticle_Source DEFAULT ('SEED'),
    IsActive     BIT            NOT NULL CONSTRAINT DF_HelpArticle_IsActive DEFAULT (1),
    ModifiedDate DATETIME       NOT NULL CONSTRAINT DF_HelpArticle_Modified DEFAULT (GETDATE())
);
GO

IF OBJECT_ID(N'dbo.HelpFeedback', N'U') IS NULL
CREATE TABLE dbo.HelpFeedback
(
    FeedbackId   INT IDENTITY(1, 1) NOT NULL CONSTRAINT PK_HelpFeedback PRIMARY KEY,
    CompanyId    INT            NOT NULL,
    ArticleCode  VARCHAR(60)    NULL,
    PageCode     NVARCHAR(100)  NULL,
    Question     NVARCHAR(500)  NULL,            -- what was asked of the Help Assistant
    Helpful      BIT            NULL,            -- NULL: a question that found no good answer
    Comment      NVARCHAR(500)  NULL,
    UserId       INT            NULL,
    CreatedDate  DATETIME       NOT NULL CONSTRAINT DF_HelpFeedback_Created DEFAULT (GETDATE())
);
GO

-- workflows (Kind FLOW) were added after the first release of this script
IF EXISTS (SELECT 1 FROM sys.check_constraints WHERE name = N'CK_HelpArticle_Kind' AND definition NOT LIKE N'%FLOW%')
BEGIN
    ALTER TABLE dbo.HelpArticle DROP CONSTRAINT CK_HelpArticle_Kind;
    ALTER TABLE dbo.HelpArticle ADD CONSTRAINT CK_HelpArticle_Kind CHECK (Kind IN ('MODULE', 'GUIDE', 'FAQ', 'TROUBLE', 'FLOW'));
END
GO

-- ── the whole catalog: menus, pages, page actions and the articles (EMR.Api builds help and search from it) ──
CREATE OR ALTER PROCEDURE dbo.usp_Help_Catalog @CompanyId INT
AS
BEGIN
    SET NOCOUNT ON;
    SELECT m.Menu_ID AS MenuId, m.Menu_Code AS MenuCode, m.Title, m.Parent_Menu_ID AS ParentMenuId, m.Sort_Order AS SortOrder, m.Icon
      FROM dbo.MenuMaster m WHERE m.CompanyId = @CompanyId AND ISNULL(m.IsActive, 1) = 1
     ORDER BY m.Sort_Order;
    SELECT p.Page_Code AS PageCode, p.Title, m.Menu_Code AS MenuCode, p.Controller, p.Action, p.Icon, p.Sort_Order AS SortOrder
      FROM dbo.PageMaster p JOIN dbo.MenuMaster m ON m.Menu_ID = p.Menu_ID
     WHERE m.CompanyId = @CompanyId AND p.IsActive = 1 AND p.Show_In_Menu = 1
     ORDER BY m.Sort_Order, p.Sort_Order;
    SELECT p.Page_Code AS PageCode, c.Title
      FROM dbo.PageControlMaster c JOIN dbo.PageMaster p ON p.Page_ID = c.Page_ID JOIN dbo.MenuMaster m ON m.Menu_ID = p.Menu_ID
     WHERE m.CompanyId = @CompanyId AND ISNULL(c.IsActive, 1) = 1 AND c.Control_Code <> 'VIEW'
     ORDER BY p.Page_Code, c.Sort_Order;
    SELECT Code, Kind, Module, Title, Summary, PageCodes, Keywords, BodyJson, SortOrder
      FROM dbo.HelpArticle WHERE IsActive = 1 ORDER BY SortOrder;
END
GO

-- the page a screen belongs to (for the ? help of the page you are on)
CREATE OR ALTER PROCEDURE dbo.usp_Help_PageByRoute @CompanyId INT, @Controller NVARCHAR(100), @Action NVARCHAR(100)
AS
BEGIN
    SET NOCOUNT ON;
    SELECT TOP 1 p.Page_Code
      FROM dbo.PageMaster p JOIN dbo.MenuMaster m ON m.Menu_ID = p.Menu_ID
     WHERE m.CompanyId = @CompanyId AND p.IsActive = 1 AND p.Controller = @Controller
     ORDER BY CASE WHEN p.Action = @Action THEN 0 WHEN p.Action = 'Index' THEN 1 ELSE 2 END, p.Show_In_Menu DESC, p.Sort_Order;
END
GO

CREATE OR ALTER PROCEDURE dbo.usp_Help_Feedback_Save
    @CompanyId INT, @ArticleCode VARCHAR(60) = NULL, @PageCode NVARCHAR(100) = NULL, @Question NVARCHAR(500) = NULL,
    @Helpful BIT = NULL, @Comment NVARCHAR(500) = NULL, @UserId INT = NULL
AS
BEGIN
    SET NOCOUNT ON;
    INSERT dbo.HelpFeedback (CompanyId, ArticleCode, PageCode, Question, Helpful, Comment, UserId)
    VALUES (@CompanyId, @ArticleCode, @PageCode, LEFT(@Question, 500), @Helpful, LEFT(@Comment, 500), @UserId);
END
GO

-- for administrators: questions with no good answer, and articles marked not helpful (last 90 days)
CREATE OR ALTER PROCEDURE dbo.usp_Help_Feedback_List @CompanyId INT
AS
BEGIN
    SET NOCOUNT ON;
    SELECT TOP 100 f.Question, f.ArticleCode, a.Title AS ArticleTitle, f.Helpful, f.Comment, f.CreatedDate,
           COALESCE(NULLIF(u.FullName, ''), u.Username) AS UserName
      FROM dbo.HelpFeedback f
      LEFT JOIN dbo.HelpArticle a ON a.Code = f.ArticleCode
      LEFT JOIN dbo.Users u ON u.Id = f.UserId
     WHERE f.CompanyId = @CompanyId AND f.CreatedDate >= DATEADD(DAY, -90, GETDATE()) AND ISNULL(f.Helpful, 0) = 0
     ORDER BY f.CreatedDate DESC;
    SELECT a.Code, a.Title, SUM(CASE WHEN f.Helpful = 1 THEN 1 ELSE 0 END) AS Helpful, SUM(CASE WHEN f.Helpful = 0 THEN 1 ELSE 0 END) AS NotHelpful
      FROM dbo.HelpFeedback f JOIN dbo.HelpArticle a ON a.Code = f.ArticleCode
     WHERE f.CompanyId = @CompanyId AND f.Helpful IS NOT NULL
     GROUP BY a.Code, a.Title ORDER BY NotHelpful DESC, Helpful DESC;
END
GO

-- ── the seeded content (replaced on every run) ──
DELETE FROM dbo.HelpArticle WHERE Source = 'SEED';
""")
    for code, kind, module, title, summary, pages, keywords, body, sort in rows:
        w("INSERT dbo.HelpArticle (Code, Kind, Module, Title, Summary, PageCodes, Keywords, BodyJson, SortOrder) VALUES ("
          f"'{code}', '{kind}', '{module}', {q(title)}, {q(summary)}, {q(pages)}, {q(keywords)}, {q(json.dumps(body, ensure_ascii=False))}, {sort});")
    w("GO")
    w("""
-- ── Utility > Help Center ──
DECLARE @co INT, @menu INT, @page INT;
DECLARE cc CURSOR LOCAL FAST_FORWARD FOR SELECT DISTINCT CompanyId FROM dbo.MenuMaster WHERE Menu_Code = N'UTILITY';
OPEN cc; FETCH NEXT FROM cc INTO @co;
WHILE @@FETCH_STATUS = 0
BEGIN
    SET @menu = (SELECT TOP 1 Menu_ID FROM dbo.MenuMaster WHERE Menu_Code = N'UTILITY' AND CompanyId = @co);
    SET @page = NULL;
    EXEC dbo.usp_Auth_PageMaster_Upsert @CompanyId = @co, @Menu_ID = @menu, @Page_Code = N'UTILITY.HELP', @Title = N'Help Center',
         @Controller = N'Help', @Action = N'Index', @Show_In_Menu = 1, @Sort_Order = 1, @Icon = N'bi bi-life-preserver me-2',
         @Route_Values = NULL, @Link_Target = NULL, @UserId = NULL, @Page_ID = @page OUTPUT;
    FETCH NEXT FROM cc INTO @co;
END
CLOSE cc; DEALLOCATE cc;
GO
""")
    w(f"PRINT 'Script 2300 applied: Help Center ({len(rows)} articles).';")
    w("GO")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print(f"{OUT}: {len(rows)} articles")


if __name__ == "__main__":
    main()
